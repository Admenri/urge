// The web shell's runtime glue.
//
// A game shipped for the browser is a directory of files behind an HTTP server
// that the module never sees: its in-memory filesystem starts out holding only
// what `--preload-file` packed into `Game.data`, and PhysicsFS can only open
// what is in there.  This file bridges the two, and it does it lazily: a file
// is fetched the first time the engine asks for it, so the page starts after a
// few kilobytes instead of the whole game.
//
// The engine's question is not a URL though.  RGSS asks for resources by name,
// and that name is case-insensitive and may leave the extension out:
//
//     Bitmap.new("Graphics/A")   ->   Graphics/A.png
//
// which a desktop answers by enumerating the directory.  There is no directory
// here, so the build writes the answer into `async_mapping.js` (see
// app/build_mapping.py) and this file indexes it:
//
//     resolveAsyncPath("graphics/a")  ->  "Graphics/A.png"
//
// `core/system/filesystem.cc` asks for that name before every open, downloads
// the file into the in-memory filesystem at its real path, and then lets
// PhysicsFS do what it always did.  Everything after the first fetch is
// ordinary filesystem work, which is what keeps the engine free of web code.

"use strict";

(function () {
  // The table generated by app/build_mapping.py, or null when this build
  // preloads its whole game instead -- then every lookup below degrades to
  // "not ours" and PhysicsFS finds the files itself.
  //
  // It is read through `typeof` rather than declared: the generated file owns
  // the binding, and a second declaration here would collide with it.
  const mapping =
    typeof asyncMappingData === "undefined" ? null : asyncMappingData;

  // Where the game's files are served from, relative to the page.
  const assetBase = "assets/";

  // Three indexes over the generated table, built once at startup.
  //
  //   exact  lowercased full path            -> entry
  //   bare   lowercased path, extension cut  -> entry
  //   dirs   lowercased directory            -> Map(lowercased name -> real name)
  //
  // `bare` is what turns "graphics/a" into Graphics/A.png; `dirs` is what lets
  // the engine enumerate a directory that has never been downloaded, which is
  // how RGSS3's `Fonts/` directory is discovered at startup.
  const exact = new Map();
  const bare = new Map();
  const dirs = new Map();

  // Real paths that are already in the in-memory filesystem, or on their way.
  const cached = new Set();

  function index(entry) {
    const path = entry.path;
    const lower = path.toLowerCase();

    if (!exact.has(lower)) exact.set(lower, entry);

    const slash = lower.lastIndexOf("/");
    const dot = lower.lastIndexOf(".");
    if (dot > slash) {
      const stem = lower.substring(0, dot);
      if (!bare.has(stem)) bare.set(stem, entry);
    }

    // Every component of the path is a child of the one before it, so a
    // directory listing can be answered from the same table.  The key is the
    // lowercased directory, because that is how the engine asks for it.
    const parts = path.split("/");
    let parent = "";
    for (const part of parts) {
      const bucketKey = parent.toLowerCase();
      let bucket = dirs.get(bucketKey);
      if (!bucket) {
        bucket = new Map();
        dirs.set(bucketKey, bucket);
      }
      bucket.set(part.toLowerCase(), part);
      parent = parent ? parent + "/" + part : part;
    }
  }

  if (mapping) {
    for (const key of Object.keys(mapping)) index(mapping[key]);
  }

  // "Graphics\\A" and "/Graphics/A/" both name the same file: RGSS paths are
  // written by the game, not by a URL builder.
  function normalize(path) {
    return String(path)
      .replace(/\\/g, "/")
      .split("/")
      .filter((part) => part && part.trim() !== "")
      .join("/");
  }

  function parentOf(path) {
    const slash = path.lastIndexOf("/");
    return slash < 0 ? "" : path.substring(0, slash);
  }

  function baseName(path) {
    const slash = path.lastIndexOf("/");
    return slash < 0 ? path : path.substring(slash + 1);
  }

  function resolve(path) {
    const key = normalize(path).toLowerCase();
    if (!key) return null;
    return exact.get(key) || bare.get(key) || null;
  }

  function ensureDir(path) {
    if (!path) return;
    let current = "";
    for (const part of path.split("/")) {
      if (!part) continue;
      current += "/" + part;
      try {
        FS.mkdir(current);
      } catch (error) {
        // Already there, which is the normal case.
      }
    }
  }

  function exists(path) {
    try {
      return FS.analyzePath("/" + path).exists;
    } catch (error) {
      return false;
    }
  }

  // The file is written under the path the manifest recorded -- real case and
  // all -- never under the spelling of the request.  The engine resolves every
  // request to that same path before it opens anything, so one file on disk
  // answers every spelling of its name, and the directory it lands in is the
  // one PhysicsFS will later enumerate.
  function materialize(entry, bytes) {
    if (exists(entry.path)) return;

    const parent = parentOf(entry.path);
    ensureDir(parent);
    FS_createDataFile("/" + parent, baseName(entry.path), bytes, true, true,
                      false);
  }

  function download(entry, done) {
    const url = assetBase + entry.path;
    const xhr = new XMLHttpRequest();
    xhr.responseType = "arraybuffer";

    Module.addRunDependency(url);

    const finish = (ok) => {
      if (!ok) cached.delete(entry.path);
      Module.removeRunDependency(url);
      done();
    };

    xhr.onload = function () {
      // Status 0 is a `file://` load, which a game opened from disk still gets.
      if (xhr.status === 200 || xhr.status === 0) {
        materialize(entry, new Uint8Array(xhr.response));
        console.log("[URGE] loaded " + entry.path + " (" + entry.size + " B)");
        finish(true);
      } else {
        console.error("[URGE] " + xhr.status + " " + xhr.statusText + ": " +
                      url);
        finish(false);
      }
    };

    xhr.onerror = function () {
      console.error("[URGE] failed to load " + url);
      finish(false);
    };

    // encodeURI keeps non-ASCII resource names -- CJK file names are common in
    // RGSS games -- as valid request targets instead of raw bytes.
    xhr.open("GET", encodeURI(url));
    xhr.send();
  }

  // ---- The engine's side of the bridge -------------------------------------

  // The real path behind a request, or null when the manifest has no such
  // file.  Called from C++ before every open, so it stays a plain lookup.
  window.resolveAsyncPath = function (path) {
    const entry = resolve(path);
    return entry ? entry.path : null;
  };

  // Whether a request still needs a download.  `true` means "nothing to
  // fetch": the file is already there, or it is not one of ours and PhysicsFS
  // will report it missing itself.
  window.isAsyncFileCached = function (path) {
    if (!mapping) return true;
    const entry = resolve(path);
    if (!entry) return true;
    return cached.has(entry.path) || exists(entry.path);
  };

  // Fetch one file and call back when it is in the filesystem.  Reached through
  // Asyncify, so the engine sees a blocking read.
  window.fetchLazyAsset = function (path, complete) {
    const done = complete || function () {};

    const entry = resolve(path);
    if (!entry) {
      console.log("[URGE] missing asset: " + normalize(path));
      return done();
    }
    if (cached.has(entry.path) || exists(entry.path)) {
      cached.add(entry.path);
      return done();
    }

    // Marked before the request goes out: a second caller for the same file
    // must not start a second download.
    cached.add(entry.path);
    download(entry, done);
  };

  // The immediate children of a directory, or null when the manifest has never
  // heard of it.  The engine merges this with whatever is really on disk.
  window.listAsyncDir = function (path) {
    const bucket = dirs.get(normalize(path).toLowerCase());
    return bucket ? Array.from(bucket.values()) : null;
  };

  // ---- Startup ------------------------------------------------------------

  // Files the manifest marked `preload` are in the filesystem before the game
  // starts: the configuration, the script archive, a container PhysicsFS has
  // to mount.  Everything else waits until it is asked for.
  function resourcePreload() {
    if (mapping) {
      for (const key of Object.keys(mapping)) {
        const entry = mapping[key];
        if (!entry.preload) continue;
        if (cached.has(entry.path) || exists(entry.path)) continue;

        cached.add(entry.path);
        download(entry, function () {});
      }
    }

    // Nothing was queued -- no manifest, or nothing marked `preload` -- so the
    // loading UI would otherwise stay up for the rest of the run.
    if (window.Module.totalDependencies === 0) showProgress(0);
  }

  const spinnerElement = document.getElementById("spinner");
  const statusElement = document.getElementById("status");

  function showProgress(left) {
    if (!spinnerElement || !statusElement) return;
    if (left) {
      statusElement.innerHTML = "Preparing... (" +
        (Module.totalDependencies - left) + "/" + Module.totalDependencies +
        ")";
    }
    spinnerElement.hidden = !left;
    statusElement.hidden = !left;
  }

  // The module object.  It has to exist before `Game.js` runs -- the runtime
  // reads `Module.canvas` and `Module.preRun` as it initializes -- which is why
  // this file is loaded ahead of it in the shell.
  window.Module = {
    canvas: document.getElementById("canvas"),
    preRun: [resourcePreload],
    totalDependencies: 0,
    print(...args) {
      console.log(...args);
    },
    printErr(...args) {
      console.error(...args);
    },
    setStatus(text) {
      if (text) console.log(text);
    },
    monitorRunDependencies(left) {
      window.Module.totalDependencies =
        Math.max(window.Module.totalDependencies, left);
      showProgress(left);
    },
  };
})();
