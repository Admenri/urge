def cc_template() -> str:
    return "\n".join(
        [
            FILE_HEADER.rstrip("\n"),
            "",
            GENERATED_INCLUDES_BEGIN,
            GENERATED_INCLUDES_END,
            "",
            HANDWRITTEN_INCLUDES_BEGIN,
            HANDWRITTEN_INCLUDES_END,
            "",
            "namespace binding {",
            "",
            HANDWRITTEN_BEGIN,
            HANDWRITTEN_END,
            "",
            GENERATED_BEGIN,
            GENERATED_END,
            "",
            HANDWRITTEN_INIT_BEGIN,
            HANDWRITTEN_INIT_END,
            "",
            "}  // namespace binding",
            "",
        ]
    )


def default_init_append(name: str) -> str:
    """The tail block a freshly generated file starts with.

    The initialiser always calls `Init<Class>BindingAppend`, so the block has
    to define it even when the class needs no patch: an empty body is a no-op
    rather than a link error, and it doubles as the place to write one, with
    the class (`klass`) or module (`mod`) the initialiser built already in
    hand.
    """
    return "\n".join(
        [
            "// Runs at the end of Init%sBinding(), with the class (`klass`) or" % name,
            "// module (`mod`) the initialiser built in hand. Patches the IR",
            "// cannot express -- a proxy class, a method whose Ruby signature",
            "// differs from its C++ one -- belong here. The block is preserved",
            "// verbatim; empty it and the generator writes this body back.",
            "void Init%sBindingAppend(VALUE klass) {" % name,
            "  (void)klass;",
            "}",
        ]
    )


def splice(text: str, begin: str, end: str, body: str) -> str:
    i = text.index(begin) + len(begin)
    j = text.index(end)
    return text[:i] + "\n" + body + text[j:]


def region(text: str, begin: str, end: str) -> str:
    i = text.index(begin) + len(begin)
    j = text.index(end)
    return text[i:j].strip("\n")


def read_text(path: str) -> str:
    with open(path, "r", encoding="utf-8", newline="") as f:
        return f.read().replace("\r\n", "\n")


def write_text(path: str, text: str) -> None:
    """Write `text` to `path`, but only if that would actually change it.

    The repository is CRLF throughout; write it that way so regenerating never
    shows up as an end-of-line diff.

    The "only if it would change" part is load-bearing, not an optimisation.
    MSBuild decides what to rebuild by comparing timestamps, so rewriting a
    file with identical bytes still counts as a change and recompiles every
    translation unit that includes it.  Nothing here depends on the write
    having happened: the generators are deterministic, so the only caller that
    could care is one that reads the file back, and none does.  Skipping the
    write is what makes a re-run of the generators free.
    """
    text = text.replace("\r\n", "\n")
    if os.path.exists(path) and read_text(path) == text:
        return
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(text)


def generate_cc(model: Model, entry: dict, path: str) -> None:
    file_name = os.path.basename(path)
    if os.path.exists(path):
        text = read_text(path)
        handwritten = region(text, HANDWRITTEN_BEGIN, HANDWRITTEN_END)
        handwritten_includes = region(
            text, HANDWRITTEN_INCLUDES_BEGIN, HANDWRITTEN_INCLUDES_END
        )
        # The tail block only exists in files written by a generator which
        # knows about it; a file from an older run gets the markers appended,
        # empty, so the run below has somewhere to put the block.
        if HANDWRITTEN_INIT_BEGIN not in text:
            text = text.replace(
                "\n}  // namespace binding",
                "\n" + HANDWRITTEN_INIT_BEGIN + "\n" + HANDWRITTEN_INIT_END
                + "\n\n}  // namespace binding",
            )
        handwritten_init = region(text, HANDWRITTEN_INIT_BEGIN, HANDWRITTEN_INIT_END)
    else:
        text = cc_template()
        handwritten = HANDWRITTEN_SEED.get(file_name, "").strip("\n")
        handwritten_includes = ""
        handwritten_init = ""

    refs = model.references(entry)
    binding_headers = ["binding_%s.h" % snake(r) for r in refs]
    # `RB_DEF_TYPE_INHERIT` names the base's data type, which its generated
    # header is what declares, so the entry's own base has to be included even
    # though no declaration of the class mentions it.
    parent = exported_parent(model, entry)
    if parent:
        binding_headers.append("binding_%s.h" % snake(parent))
    binding_headers = sorted(set(binding_headers))
    core_headers = sorted({entry["header"]} | {model.by_cpp_name[r]["header"] for r in refs})

    includes = ["#include \"binding_%s.h\"" % snake(entry["cpp_name"]), ""]
    includes += ["#include \"%s\"" % h for h in binding_headers]
    if binding_headers:
        includes.append("")
    includes += ["#include \"%s\"" % h for h in core_headers]

    text = splice(
        text, GENERATED_INCLUDES_BEGIN, GENERATED_INCLUDES_END,
        "\n".join(includes).strip("\n") + "\n",
    )
    text = splice(
        text, HANDWRITTEN_INCLUDES_BEGIN, HANDWRITTEN_INCLUDES_END,
        (handwritten_includes + "\n") if handwritten_includes else "",
    )
    text = splice(
        text, HANDWRITTEN_BEGIN, HANDWRITTEN_END,
        (handwritten + "\n") if handwritten else "",
    )
    # An empty tail block still has to define the function the generated
    # initialiser calls, so the default body is emitted when nothing is there.
    tail = handwritten_init or default_init_append(entry["cpp_name"])
    text = splice(
        text, HANDWRITTEN_INIT_BEGIN, HANDWRITTEN_INIT_END,
        tail + "\n",
    )

    body = emit_module(entry) if entry["kind"] == "module" else emit_class(model, entry)
    text = splice(text, GENERATED_BEGIN, GENERATED_END, "\n".join(body).strip("\n") + "\n")
    write_text(path, text)


def generate_init(model: Model, out_dir: str) -> None:
    write_text(
        os.path.join(out_dir, "binding_init.h"),
        """\
#pragma once

// Generated by bind/generate_binding.py -- do not edit.
// Rules: bind/Bindgen.md

#include "cruby_utils.h"

namespace binding {

// Defines the RGSS exception classes, every exported class and every exported
// module, in dependency order. Requires a live Ruby VM (`ruby_init()` must have
// run first) and redefines the classes when called again, so call it once.
void InitBindings();

}  // namespace binding
""",
    )

    path = os.path.join(out_dir, "binding_init.cc")
    if os.path.exists(path):
        text = read_text(path)
        handwritten = region(text, HANDWRITTEN_BEGIN, HANDWRITTEN_END)
    else:
        text = cc_template()
        handwritten = HANDWRITTEN_SEED.get("binding_init.cc", "").strip("\n")

    includes = ["#include \"binding_init.h\"", ""]
    includes += ['#include "binding_%s.h"' % snake(e["cpp_name"]) for e in model.all_entries()]
    body = [
        "namespace {",
        "",
        "// The RGSS exception classes the glue raises. A host entry point may",
        "// define them first, with parent classes of its own; this is the fallback",
        "// which keeps the binding library self sufficient.",
        "void DefineRGSSExceptions() {",
        "  if (NIL_P(g_reset_exception))",
        '    g_reset_exception = rb_define_class("RGSSReset", rb_eStandardError);',
        "  if (NIL_P(g_rgss_exception))",
        '    g_rgss_exception = rb_define_class("RGSSError", rb_eStandardError);',
        "}",
        "",
        "}  // namespace",
        "",
        "void InitBindings() {",
        "  DefineRGSSExceptions();",
        "",
    ]
    body += ["  Init%sBinding();" % e["cpp_name"] for e in model.all_entries()]
    body += ["  " + call for call in EXTRA_INIT_BINDING_CALLS]
    body.append("}")

    text = splice(
        text, GENERATED_INCLUDES_BEGIN, GENERATED_INCLUDES_END,
        "\n".join(includes).strip("\n") + "\n",
    )
    text = splice(
        text, HANDWRITTEN_BEGIN, HANDWRITTEN_END,
        (handwritten + "\n") if handwritten else "",
    )
    text = splice(text, GENERATED_BEGIN, GENERATED_END, "\n".join(body) + "\n")
    write_text(path, text)


def prune_stale_outputs(model: Model, out_dir: str) -> list[tuple[str, bool]]:
    """Remove generated files whose entry is no longer in the IR.

    A class dropped from `core/` leaves `binding_<name>.{h,cc}` behind, and
    nothing else would ever clean them up: `bind/CMakeLists.txt` globs `*.cc`,
    so the leftovers keep being compiled -- against an API that no longer
    exists, which fails the build while pointing at a file nobody edited.

    "Should still exist" is decided by the IR, which is the only model this
    script has.  Two consequences worth stating, because they are deliberate:

      * a class that is still in `core/` but is no longer exported counts as
        gone.  Its glue would still compile against the class, but nothing
        calls the glue, and the file has already stopped tracking its header;
      * a rename is two different entries, so the old pair is removed and the
        new pair written in the same run.

    Hand-written *blocks* inside a generated file are not a reason to keep it:
    once the entry is gone there is no file to splice them back into, and the
    entry's fate decides theirs (see Bindgen.md, "残留文件清理").

    Only files whose banner carries GENERATED_MARKER are removed, so a
    hand-written file that merely matches `binding_*` survives.
    """
    entries = model.all_entries()
    if not entries:
        # A header the parser cannot read yields an empty model.  Sweeping on
        # that would delete the entire directory, so refuse and say so.
        print("  WARNING: the IR lists no entries -- skipping the stale-file sweep")
        return []

    expected = {"binding_init.h", "binding_init.cc"}
    for entry in entries:
        stem = "binding_%s" % snake(entry["cpp_name"])
        expected.add(stem + ".h")
        expected.add(stem + ".cc")

    removed: list[tuple[str, bool]] = []
    for name in sorted(os.listdir(out_dir)):
        if name in expected or not BINDING_OUTPUT_RE.match(name):
            continue
        path = os.path.join(out_dir, name)
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as f:
                text = f.read()
        except OSError:
            continue
        if GENERATED_MARKER not in text[:400]:
            print("  kept %s: not generated by this script" % name)
            continue
        # `region` uses str.index and raises on a missing marker, which is the
        # normal case for the `.h` files (they have no HANDWRITTEN block).
        if HANDWRITTEN_BEGIN in text and HANDWRITTEN_END in text:
            handwritten = region(text, HANDWRITTEN_BEGIN, HANDWRITTEN_END)
        else:
            handwritten = ""
        os.remove(path)
        removed.append((name, bool(handwritten.strip())))
    return removed


def main() -> int:
    ir_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_IR
    out_dir = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
    with open(ir_path, "r", encoding="utf-8") as f:
        model = Model(json.load(f))

    for entry in model.all_entries():
        if entry["kind"] == "class":
            header = CLASS_HEADER % (entry["cpp_name"], entry["cpp_name"])
        else:
            header = MODULE_HEADER % entry["cpp_name"]
        write_text(os.path.join(out_dir, "binding_%s.h" % snake(entry["cpp_name"])), header)
        generate_cc(model, entry, os.path.join(out_dir, "binding_%s.cc" % snake(entry["cpp_name"])))
    generate_init(model, out_dir)

    print(
        "Generated %d classes, %d modules in %s"
        % (
            len(model.classes),
            len(model.modules),
            os.path.relpath(out_dir, REPO_ROOT).replace("\\", "/"),
        )
    )
    print("  marshalable: %s" % ", ".join(sorted(model.marshalable)))

    removed = prune_stale_outputs(model, out_dir)
    if removed:
        print("  removed %d file(s) whose entry is gone from the IR:" % len(removed))
        for name, had_handwritten in removed:
            print("    %s%s" % (name, "  [had hand-written glue]" if had_handwritten else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
