def emit_initialize(entry: dict) -> list[str]:
    name = entry["cpp_name"]
    dispatch = Dispatch(entry["constructors"])
    lines = ["  urge::RefPtr<urge::%s> obj = nullptr;" % name]

    def invoke(args: list[str], indent: str) -> list[str]:
        call = "obj = urge::MakeRefCounted<urge::%s>(%s)" % (name, ", ".join(args))
        return emit_call(call, indent)

    lines.extend(emit_framework("initialize", dispatch, invoke, "return SetupSelfData(self, obj.get());"))
    return ["RB_FUNC(%s_initialize) {" % name] + lines + ["}"]


def emit_initialize_copy(entry: dict) -> list[str]:
    name = entry["cpp_name"]
    return [
        "RB_FUNC(%s_initialize_copy) {" % name,
        "  VALUE other;",
        '  ParseArgs(argc, argv, "o", &other);',
        "",
        "  urge::RefPtr<urge::%s> obj = nullptr;" % name,
        "  EXC_BEGIN {",
        "    auto other_obj = GetObject<urge::%s>(other, k%sDataType);" % (name, name),
        "    obj = urge::MakeRefCounted<urge::%s>(other_obj);" % name,
        "  }",
        "  EXC_END;",
        "",
        "  return SetupSelfData(self, obj.get());",
        "}",
    ]


def emit_marshal(entry: dict) -> list[str]:
    name = entry["cpp_name"]
    return [
        "RB_FUNC(%s__dump) {" % name,
        "  auto* self_obj = GetSelfData<urge::%s>(self);" % name,
        "",
        "  EXC_BEGIN {",
        "    std::string result =",
        "        urge::%s::MarshalDump(urge::RefPtr<urge::%s>(self_obj));" % (name, name),
        "    return rb_str_new(result.data(), static_cast<long>(result.size()));",
        "  }",
        "  EXC_END;",
        "  return Qnil;",
        "}",
        "",
        "RB_FUNC(%s__load) {" % name,
        "  std::string data;",
        '  ParseArgs(argc, argv, "s", &data);',
        "",
        "  EXC_BEGIN {",
        "    VALUE obj = rb_obj_alloc(self);",
        "    auto ptr = urge::%s::MarshalLoad(data);" % name,
        "    return SetupSelfData(obj, ptr.get());",
        "  }",
        "  EXC_END;",
        "  return Qnil;",
        "}",
    ]


def emit_method(entry: dict, group: list[dict], is_static: bool) -> list[str]:
    name = entry["cpp_name"]
    head = group[0]
    dispatch = Dispatch(group)
    symbol = "%s_%s" % (name, head["cpp_name"])
    if is_static:
        receiver = "urge::%s::%s" % (name, head["cpp_name"])
    else:
        receiver = "self_obj->%s" % head["cpp_name"]
    return_type = head["return"]["cpp_type"]

    def invoke(args: list[str], indent: str) -> list[str]:
        return emit_return(return_type, "%s(%s)" % (receiver, ", ".join(args)), indent)

    lines = ["RB_FUNC(%s) {" % symbol]
    if not is_static:
        lines.append("  auto* self_obj = GetSelfData<urge::%s>(self);" % name)
        lines.append("")
    lines.extend(emit_framework(head["ruby_name"], dispatch, invoke, "return Qnil;"))
    lines.append("}")
    return lines


def attr_macro(entry: dict, attr: dict, static: bool, marshalable: set[str]) -> str:
    cpp_type = attr["cpp_type"]
    name = attr["cpp_name"]
    owner = entry["cpp_name"]
    inner = refptr_inner(cpp_type)
    if inner is not None:
        if static:
            return "BINDING_CLASS_ATTR_OBJECT(%s, urge::%s, %s, urge::%s, k%sDataType);" % (
                owner, owner, name, inner, inner,
            )
        macro = "BINDING_ATTR_OBJECT" if inner in marshalable else "BINDING_ATTR_OBJECT_REF"
        return "%s(%s, urge::%s, %s, urge::%s, k%sDataType);" % (
            macro, owner, owner, name, inner, inner,
        )
    prefix = "BINDING_CLASS_ATTR" if static else "BINDING_ATTR"
    if cpp_type in INT_RETURNS:
        suffix = "INT"
    elif cpp_type in ("float", "double"):
        suffix = "FLOAT"
    elif cpp_type == "bool":
        suffix = "BOOL"
    elif cpp_type == "std::vector<std::string>":
        suffix = "STRINGVECTOR"
    else:
        raise ValueError("no attribute macro for %r" % cpp_type)
    return "%s_%s(%s, urge::%s, %s);" % (prefix, suffix, owner, owner, name)


def emit_init_function(entry: dict) -> list[str]:
    name = entry["cpp_name"]
    lines = [
        # The tail block is written after this one in the file, so the call
        # below needs the declaration.
        "void Init%sBindingAppend(VALUE klass);" % name,
        "",
        "void Init%sBinding() {" % name,
    ]
    if entry["ruby_superclass"] == "Object":
        lines.append('  auto klass = rb_define_class("%s", rb_cObject);' % name)
    else:
        lines.append(
            '  auto parent = rb_const_get(rb_cObject, rb_intern("%s"));'
            % entry["ruby_superclass"]
        )
        lines.append('  auto klass = rb_define_class("%s", parent);' % name)
    lines.append("  rb_define_alloc_func(klass, ClassAllocate<&k%sDataType>);" % name)
    lines.append("")

    if entry["constructors"]:
        lines.append('  DefineMethod(klass, "initialize", %s_initialize);' % name)
    if entry["initialize_copy"]:
        lines.append('  DefineMethod(klass, "initialize_copy", %s_initialize_copy);' % name)
    for group in group_overloads(entry["instance_methods"]):
        lines.append(
            '  DefineMethod(klass, "%s", %s_%s);'
            % (group[0]["ruby_name"], name, group[0]["cpp_name"])
        )
    for key in ("get", "set"):
        item = (entry["index"] or {}).get(key)
        if item:
            lines.append(
                '  DefineMethod(klass, "%s", %s_%s);'
                % (item["ruby_name"], name, item["cpp_name"])
            )
    if entry["marshal"]["dump"] and entry["marshal"]["load"]:
        lines.append('  DefineMethod(klass, "_dump", %s__dump);' % name)
        lines.append('  DefineClassMethod(klass, "_load", %s__load);' % name)
    for group in group_overloads(entry["class_methods"]):
        lines.append(
            '  DefineClassMethod(klass, "%s", %s_%s);'
            % (group[0]["ruby_name"], name, group[0]["cpp_name"])
        )
    for attr in entry["attributes"]:
        lines.append('  DefineMethod(klass, "%s", %s_%s);' % (attr["name"], name, attr["cpp_name"]))
        lines.append(
            '  DefineMethod(klass, "%s", %s_%sEqual);' % (attr["setter"], name, attr["cpp_name"])
        )
    for attr in entry["class_attributes"]:
        lines.append(
            '  DefineClassMethod(klass, "%s", %s_%s);' % (attr["name"], name, attr["cpp_name"])
        )
        lines.append(
            '  DefineClassMethod(klass, "%s", %s_%sEqual);'
            % (attr["setter"], name, attr["cpp_name"])
        )
    lines.extend("  " + call for call in EXTRA_INIT_CALLS.get(name, []))
    lines.append("  Init%sBindingAppend(klass);" % name)
    lines.append("}")
    return lines


def emit_class(model: Model, entry: dict) -> list[str]:
    name = entry["cpp_name"]
    parent = exported_parent(model, entry)
    # The data type of a derived class points at its base's so that a value of
    # it is accepted where the base is expected; only an exported base has a
    # data type to point at.  See cruby_utils.h / Bindgen.md.
    declaration = (
        "RB_DEF_TYPE_INHERIT(%s, %s);" % (name, parent)
        if parent
        else "RB_DEF_TYPE(%s);" % name
    )
    lines = [
        "// " + "-" * 73,
        "// %s  (%s)" % (name, entry["export"]),
        "// " + "-" * 73,
        "",
        declaration,
        "",
    ]
    if entry["constructors"]:
        lines.extend(emit_initialize(entry))
        lines.append("")
    if entry["initialize_copy"]:
        lines.extend(emit_initialize_copy(entry))
        lines.append("")
    if entry["marshal"]["dump"] and entry["marshal"]["load"]:
        lines.extend(emit_marshal(entry))
        lines.append("")
    for group in group_overloads(entry["instance_methods"]):
        lines.extend(emit_method(entry, group, False))
        lines.append("")
    for group in group_overloads(entry["class_methods"]):
        lines.extend(emit_method(entry, group, True))
        lines.append("")
    for attr in entry["attributes"]:
        lines.append("// Attribute: %s (%s)" % (attr["name"], attr["cpp_type"]))
        lines.extend(format_macro(attr_macro(entry, attr, False, model.marshalable)))
        lines.append("")
    for attr in entry["class_attributes"]:
        lines.append("// Class attribute: %s (%s)" % (attr["name"], attr["cpp_type"]))
        lines.extend(format_macro(attr_macro(entry, attr, True, model.marshalable)))
        lines.append("")
    lines.extend(emit_init_function(entry))
    return lines


