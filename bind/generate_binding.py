def param_plan(cpp_type: str, name: str):
    """Everything one argument costs: `(format, decls, parse targets, checks, arg)`.

    `decls` is a list of `(type, name)` pairs -- plain data only -- and `checks`
    are the statements that validate the parsed VALUE and fill in the raw form.
    `arg` is what goes into the C++ call; it is evaluated inside phase 2, which
    is where an owning temporary is allowed to live.
    """
    inner = refptr_inner(cpp_type)
    if inner is not None:
        # `MaybePtr<T>` is the parameter saying `nil` is a value; anything else
        # is required, and `CheckObject` raises `TypeError` for `nil` -- the
        # same answer `rb_check_typeddata` gives any other wrong type.  That is
        # what lets the engine drop its own null checks.
        check = "CheckMaybeObject" if refptr_is_maybe(cpp_type) else "CheckObject"
        return (
            "o",
            [("VALUE", name + "_val"), ("urge::%s*" % inner, name)],
            [name + "_val"],
            ["%s = %s<urge::%s>(%s_val, k%sDataType);"
             % (name, check, inner, name, inner)],
            name,
        )
    element = vector_codec(cpp_type)
    if element is not None:
        return (
            "o",
            [("VALUE", name + "_val")],
            [name + "_val"],
            ["CheckVectorOf<%s>(%s_val);" % (element, name)],
            "TakeVectorOf<%s>(%s_val)" % (element, name),
        )
    if cpp_type == "std::string":
        return (
            "o",
            [
                ("VALUE", name + "_val"),
                ("const char*", name + "_data"),
                ("size_t", name + "_size"),
            ],
            [name + "_val"],
            ["CheckString(%s_val, &%s_data, &%s_size);" % (name, name, name)],
            "std::string(%s_data, %s_size)" % (name, name),
        )
    fmt, local_type, template = SCALAR_PARAMS[cpp_type]
    return (fmt, [(local_type, name)], [name], [], template.format(n=name))


class ParamPlan:
    """Everything phase 1 needs for one argument list."""

    def __init__(self, params: list[dict]):
        self.params = params
        self.declarations: list[str] = []
        self.format = ""
        self.args: list[str] = []
        self.checks: list[str] = []
        self.parse_targets: list[str] = []
        # Grouped so that `int x, y;` stays one line.  A pointer type is never
        # grouped: `urge::Rect* a, b;` would declare `b` as a `urge::Rect`.
        groups: list[tuple[str, str, list[str]]] = []
        for p in params:
            fmt, decls, targets, checks, arg = param_plan(p["type"], p["name"])
            self.format += fmt
            self.parse_targets.extend(targets)
            self.checks.extend(checks)
            self.args.append(arg)
            for type_name, local in decls:
                key = type_name if not type_name.endswith("*") else type_name + local
                for known, _, names in groups:
                    if known == key:
                        names.append(local)
                        break
                else:
                    groups.append((key, type_name, [local]))
        for _, type_name, names in groups:
            self.declarations.append("%s %s;" % (type_name, ", ".join(names)))

    def parse_args_lines(self, indent: str) -> list[str]:
        if not self.format:
            return []
        pointers = ", ".join("&" + name for name in self.parse_targets)
        return emit_call(
            'ParseArgs(argc, argv, "%s", %s)' % (self.format, pointers), indent
        )


def return_slot(cpp_type: str) -> list[str]:
    """The declarations phase 1 must carry for phase 3 to convert the result.

    Owning results are boxed: a `std::string` or a `std::vector` cannot live in
    the phase-1/phase-3 frame, because that frame has to stay destructor free,
    and it has to survive phase 2's scope.  The box is deleted in phase 3; it
    leaks only if the Ruby conversion raises, which is NoMemoryError.
    """
    if cpp_type == "void":
        return []
    if cpp_type == "bool":
        return ["bool result = false;"]
    if cpp_type in INT_RETURNS:
        return ["%s result = 0;" % INT_RETURNS_SLOT[cpp_type]]
    if cpp_type in ("float", "double"):
        return ["double result = 0.0;"]
    if cpp_type == "std::string":
        return ["std::string* result = nullptr;"]
    if cpp_type in ("const char*", "char*"):
        return ["const char* result = nullptr;"]
    element = vector_codec(cpp_type)
    if element is not None:
        return ["std::vector<%s>* result = nullptr;" % element]
    inner = refptr_inner(cpp_type)
    if inner is not None:
        return ["urge::%s* result = nullptr;" % inner]
    raise ValueError("no result slot for %r" % cpp_type)


# The C++ type a scalar result is carried in, which is not the same as the
# function's declared return type for the narrow integers.
INT_RETURNS_SLOT = {
    "int8_t": "int32_t",
    "int16_t": "int32_t",
    "int32_t": "int32_t",
    "int": "int32_t",
    "uint8_t": "uint32_t",
    "uint16_t": "uint32_t",
    "uint32_t": "uint32_t",
    "unsigned int": "uint32_t",
    "int64_t": "int64_t",
    "uint64_t": "uint64_t",
}


def emit_store(cpp_type: str, call: str, indent: str) -> list[str]:
    """Phase 2: run the call and park its result in the slot."""
    if cpp_type == "void":
        return emit_call(call, indent)
    if cpp_type == "std::string":
        return emit_call("result = new std::string(%s)" % call, indent)
    element = vector_codec(cpp_type)
    if element is not None:
        return emit_call("result = new std::vector<%s>(%s)" % (element, call), indent)
    inner = refptr_inner(cpp_type)
    if inner is not None:
        # The `RefPtr` temporary dies with phase 2, so the slot takes its own
        # reference; phase 3 releases it once the Ruby object owns one too.
        return (
            emit_call("urge::RefPtr<urge::%s> value = %s" % (inner, call), indent)
            + [indent + "result = value.get();"]
            + [indent + "if (result)"]
            + [indent + "  result->AddRef();"]
        )
    return emit_call("result = %s" % call, indent)


def emit_convert(cpp_type: str, indent: str) -> list[str]:
    """Phase 3: turn the slot into a Ruby value (or a bare `nil`)."""
    if cpp_type == "void":
        return [indent + "return Qnil;"]
    if cpp_type == "bool":
        return [indent + "return result ? Qtrue : Qfalse;"]
    if cpp_type in INT_RETURNS:
        return [indent + "return %s(result);" % INT_RETURNS[cpp_type]]
    if cpp_type in ("float", "double"):
        return [indent + "return rb_float_new(result);"]
    if cpp_type == "std::string":
        return [
            indent + "VALUE value = rb_enc_str_new(",
            indent + "    result->data(), static_cast<long>(result->size()),",
            indent + "    rb_utf8_encoding());",
            indent + "delete result;",
            indent + "return value;",
        ]
    element = vector_codec(cpp_type)
    if element is not None:
        return [
            indent + "VALUE value = WrapVectorOf<%s>(*result);" % element,
            indent + "delete result;",
            indent + "return value;",
        ]
    inner = refptr_inner(cpp_type)
    if inner is not None:
        return [
            indent + "VALUE value = WrapObject(result, k%sDataType);" % inner,
            indent + "if (result)",
            indent + "  result->Release();",
            indent + "return value;",
        ]
    if cpp_type in ("const char*", "char*"):
        # rubies this old have no rb_utf8_str_new_cstr, and the pointer may be
        # null, so measure it instead of relying on a NUL-terminated wrapper.
        return [
            indent + "return result",
            indent + "           ? rb_enc_str_new(result,",
            indent + "                            static_cast<long>(std::strlen(result)),",
            indent + "                            rb_utf8_encoding())",
            indent + "           : Qnil;",
        ]
    raise ValueError("no return conversion for %r" % cpp_type)


def arity_map(overloads: list[dict]) -> dict[int, dict]:
    """Map `argc` to the overload serving it, rejecting ambiguities."""
    covered: dict[int, dict] = {}
    for ov in overloads:
        params = ov["params"]
        if any(p["name"] == "..." for p in params):
            raise ValueError("variadic declarations are not supported")
        required = sum(1 for p in params if p.get("default") is None)
        for k in range(required, len(params) + 1):
            if k in covered:
                raise ValueError(
                    "ambiguous overload for argc=%d: %s vs %s"
                    % (k, covered[k]["cpp_name"], ov["cpp_name"])
                )
            covered[k] = ov
    return covered


def group_overloads(entries: list[dict]) -> list[list[dict]]:
    groups: dict[str, list[dict]] = {}
    order: list[str] = []
    for e in entries:
        if e["cpp_name"] not in groups:
            groups[e["cpp_name"]] = []
            order.append(e["cpp_name"])
        groups[e["cpp_name"]].append(e)
    return [groups[k] for k in order]


class Dispatch:
    """The `argc`-branch decision for one C++ declaration."""

    def __init__(self, overloads: list[dict]):
        self.overloads = overloads
        self.covered = arity_map(overloads)
        self.arities = sorted(self.covered)
        # A single fully specified shape needs no branches: CheckArgc answers
        # both the missing- and the extra-argument case on its own.
        self.simple = len(self.arities) == 1 and all(
            p.get("default") is None for p in self.covered[self.arities[0]]["params"]
        )

    def variants(self) -> list[list[dict]]:
        if self.simple:
            return [self.covered[self.arities[0]]["params"]]
        return [self.covered[k]["params"][:k] for k in self.arities]

    def variants_with_exception(self) -> list[tuple[list[dict], bool]]:
        """The arities plus whether each one's declaration carries the state.

        Overloads of one name may disagree -- `Bitmap(filename)` reports, the
        `Bitmap(width, height)` that follows it cannot -- so the flag travels
        with the variant instead of with the name.
        """
        if self.simple:
            only = self.covered[self.arities[0]]
            return [(only["params"], only.get("has_exception", False))]
        return [(self.covered[k]["params"][:k],
                 self.covered[k].get("has_exception", False))
                for k in self.arities]


def emit_framework(
    ruby_name: str,
    dispatch: Dispatch,
    call_of,
    return_type: str,
    has_exception: bool = False,
    indent: str = "  ",
) -> list[str]:
    """Emit the body of a binding.

    Phase 1 (Ruby -> C) validates and parses into plain data and may raise.
    The engine call runs in its own scope, which is the only place an owning
    temporary may live.  Phase 3 (C++ -> Ruby) converts the slot back and may
    raise again.

    `has_exception` is the declaration's `URGE_EXCEPT` marker: when it is set
    the call is handed a state of its own and `RaiseException` turns whatever
    the engine recorded into a Ruby exception.  Without it the call cannot
    fail and no state exists at all.

    The frame holds bare data only, which is what lets both phases raise; see
    the block comment on `ExceptionState` in core/common/exception.h.
    """
    slot = return_slot(return_type)
    lines: list[str] = []

    def emit_arity(params, nested, keyword, argc_check, has_exception):
        plan = ParamPlan(params)
        if has_exception:
            lines.append(nested + "urge::ExceptionState exception_state;")
        if argc_check is not None:
            lines.append(nested + "CheckArgc(argc, %d);" % argc_check)
        lines.extend(nested + d for d in plan.declarations)
        lines.extend(plan.parse_args_lines(nested))
        lines.extend(nested + c for c in plan.checks)
        if plan.declarations or plan.format or has_exception:
            lines.append("")
        lines.extend(nested + d for d in slot)
        if slot:
            lines.append("")
        args = list(plan.args)
        if has_exception:
            args.insert(0, "exception_state")
        lines.append(nested + "{")
        lines.extend(emit_store(return_type, call_of(args), nested + "  "))
        lines.append(nested + "}")
        if has_exception:
            lines.append(nested + "RaiseException(exception_state);")
        lines.append("")
        lines.extend(emit_convert(return_type, nested))

    variants = dispatch.variants_with_exception()
    if dispatch.simple:
        params, has_exception = variants[0]
        emit_arity(params, indent, None, len(params), has_exception)
    else:
        nested = indent + "  "
        for index, (params, has_exception) in enumerate(variants):
            keyword = "if" if index == 0 else "} else if"
            lines.append("%s%s (argc == %d) {" % (indent, keyword, len(params)))
            lines.append(
                "%s// %s(%s)"
                % (nested, ruby_name, ", ".join(p["name"] for p in params))
            )
            emit_arity(params, nested, keyword, None, has_exception)
        lines.append("%s} else {" % indent)
        # Several arities are valid, so the message cannot name one expected
        # count.
        lines.append("%s  ArgcError(argc);" % indent)
        lines.append("%s}" % indent)
    return lines


def emit_initialize(entry: dict) -> list[str]:
    name = entry["cpp_name"]
    dispatch = Dispatch(entry["constructors"])
    lines = ["RB_FUNC(%s_initialize) {" % name]

    def emit_arity(params, nested, has_exception):
        plan = ParamPlan(params)
        if has_exception:
            lines.append(nested + "urge::ExceptionState exception_state;")
        lines.extend(nested + d for d in plan.declarations)
        lines.extend(plan.parse_args_lines(nested))
        lines.extend(nested + c for c in plan.checks)
        lines.append("")
        lines.append(nested + "urge::%s* result = nullptr;" % name)
        lines.append("")
        args = list(plan.args)
        if has_exception:
            args.insert(0, "exception_state")
        lines.append(nested + "{")
        inner = nested + "  "
        # `MakeRefCounted` answers a `RefPtr` that dies with the scope, so the
        # slot takes its own reference; the wrapper is handed that one.
        lines.extend(
            emit_call(
                "urge::RefPtr<urge::%s> value = "
                "urge::MakeRefCounted<urge::%s>(%s)"
                % (name, name, ", ".join(args)),
                inner,
            )
        )
        lines.append(inner + "result = value.get();")
        lines.append(inner + "if (result)")
        lines.append(inner + "  result->AddRef();")
        lines.append(nested + "}")
        if has_exception:
            lines.append(nested + "RaiseException(exception_state);")
        lines.append("")
        lines.append(nested + "VALUE object = SetupSelfData(self, result);")
        lines.append(nested + "if (result)")
        lines.append(nested + "  result->Release();")
        lines.append(nested + "return object;")

    variants = dispatch.variants_with_exception()
    if dispatch.simple:
        params, has_exception = variants[0]
        emit_arity(params, "  ", has_exception)
    else:
        nested = "    "
        for index, (params, has_exception) in enumerate(variants):
            keyword = "if" if index == 0 else "} else if"
            lines.append("  %s (argc == %d) {" % (keyword, len(params)))
            lines.append(
                "%s// initialize(%s)"
                % (nested, ", ".join(p["name"] for p in params))
            )
            emit_arity(params, nested, has_exception)
        lines.append("  } else {")
        lines.append("    ArgcError(argc);")
        lines.append("  }")
    lines.append("}")
    return lines


def emit_initialize_copy(entry: dict) -> list[str]:
    name = entry["cpp_name"]
    copy = entry["initialize_copy"]
    has_exception = copy.get("has_exception", False)
    ctor_args = "exception_state, other_obj" if has_exception else "other_obj"
    lines = [
        "RB_FUNC(%s_initialize_copy) {" % name,
    ]
    if has_exception:
        lines.append("  urge::ExceptionState exception_state;")
    lines.extend(
        [
            "  VALUE other_val = Qnil;",
            "  CheckArgc(argc, 1);",
            '  ParseArgs(argc, argv, "o", &other_val);',
            "  urge::%s* other_obj = CheckObject<urge::%s>(other_val, k%sDataType);"
            % (name, name, name),
            "",
            "  urge::%s* result = nullptr;" % name,
            "",
            "  {",
            "    urge::RefPtr<urge::%s> value = "
            "urge::MakeRefCounted<urge::%s>(%s);"
            % (name, name, ctor_args),
            "    result = value.get();",
            "    if (result)",
            "      result->AddRef();",
            "  }",
        ]
    )
    if has_exception:
        lines.append("  RaiseException(exception_state);")
    lines.extend(
        [
            "",
            "  VALUE object = SetupSelfData(self, result);",
            "  if (result)",
            "    result->Release();",
            "  return object;",
            "}",
        ]
    )
    return lines


def emit_marshal(entry: dict) -> list[str]:
    name = entry["cpp_name"]
    # `_dump` is called with the depth argument, so it takes one and ignores it;
    # `_load` takes exactly the string.
    # `_dump` takes the depth argument and ignores it, so it cannot go through
    # `emit_framework`: that would emit a `CheckArgc(argc, 0)` and reject every
    # real call from Marshal.
    lines = [
        "RB_FUNC(%s__dump) {" % name,
        "  auto* self_obj = GetSelfData<urge::%s>(self);" % name,
        "",
        "  std::string* result = nullptr;",
        "",
        "  {",
        "    result = new std::string(urge::%s::MarshalDump("
        "urge::RefPtr<urge::%s>(self_obj)));" % (name, name),
        "  }",
        "",
    ]
    lines.extend(emit_convert("std::string", "  "))
    lines.append("}")
    lines.append("")
    lines.extend(
        [
            "RB_FUNC(%s__load) {" % name,
            "  VALUE data_val = Qnil;",
            "  CheckArgc(argc, 1);",
            '  ParseArgs(argc, argv, "o", &data_val);',
            "  const char* data_data;",
            "  size_t data_size;",
            "  CheckString(data_val, &data_data, &data_size);",
            "",
            "  urge::ExceptionState exception_state;",
            "  urge::%s* result = nullptr;" % name,
            "",
            "  {",
            "    urge::RefPtr<urge::%s> value ="
            " urge::%s::MarshalLoad(exception_state,"
            " std::string(data_data, data_size));" % (name, name),
            "    result = value.get();",
            "    if (result)",
            "      result->AddRef();",
            "  }",
            "  RaiseException(exception_state);",
            "",
            "  VALUE object = SetupSelfData(rb_obj_alloc(self), result);",
            "  if (result)",
            "    result->Release();",
            "  return object;",
            "}",
        ]
    )
    return lines


def emit_equal(entry: dict) -> list[str]:
    """`==`, `eql?` and `===` for a value class (the `KLASS_EQUAL` marker).

    One C++ operator serves all three names, which is why this is emitted here
    instead of going through `emit_method`: the marker names no C++ function the
    method emitter could call.  A foreign object is *not equal* rather than a
    `TypeError` -- `==` is expected to answer, not to raise.
    """
    name = entry["cpp_name"]
    return [
        "// Value equality: ==, eql?, === (KLASS_EQUAL)",
        "RB_FUNC(%s__equal) {" % name,
        "  auto* self_obj = GetSelfData<urge::%s>(self);" % name,
        "  VALUE other_val = Qnil;",
        "  CheckArgc(argc, 1);",
        '  ParseArgs(argc, argv, "o", &other_val);',
        "",
        "  if (!rb_typeddata_is_kind_of(other_val, &k%sDataType))" % name,
        "    return Qfalse;",
        "  auto* other_obj = GetSelfData<urge::%s>(other_val);" % name,
        "",
        "  bool result = false;",
        "",
        "  {",
        "    result = *self_obj == *other_obj;",
        "  }",
        "",
        "  return result ? Qtrue : Qfalse;",
        "}",
    ]


def emit_method(entry: dict, group: list[dict], is_static: bool) -> list[str]:
    name = entry["cpp_name"]
    head = group[0]
    dispatch = Dispatch(group)
    symbol = "%s_%s" % (name, head["cpp_name"])
    if is_static:
        receiver = "urge::%s::%s" % (name, head["cpp_name"])
    else:
        receiver = "self_obj->%s" % head["cpp_name"]
    return_type = head["return"]["cpp_type"]

    def call_of(args):
        return "%s(%s)" % (receiver, ", ".join(args))

    lines = ["RB_FUNC(%s) {" % symbol]
    if not is_static:
        lines.append("  auto* self_obj = GetSelfData<urge::%s>(self);" % name)
        lines.append("")
    lines.extend(
        emit_framework(head["ruby_name"], dispatch, call_of, return_type,
                       head.get("has_exception", False))
    )
    lines.append("}")
    return lines


def attr_macro(entry: dict, attr: dict, static: bool, marshalable: set[str]) -> str:
    cpp_type = attr["cpp_type"]
    name = attr["cpp_name"]
    owner = entry["cpp_name"]
    has_exception = attr.get("has_exception", False)
    inner = refptr_inner(cpp_type)
    if inner is not None:
        # The last argument names the phase-1 check, which is where the null
        # contract of `ATTR(RefPtr<T>, ...)` vs `ATTR(MaybePtr<T>, ...)` lands.
        check = "CheckMaybeObject" if refptr_is_maybe(cpp_type) else "CheckObject"
        if static:
            if has_exception:
                raise ValueError("no static ATTR_EXC macro yet: %s.%s" %
                                 (owner, name))
            return (
                "BINDING_CLASS_ATTR_OBJECT(%s, urge::%s, %s, urge::%s, "
                "k%sDataType, %s);"
                % (owner, owner, name, inner, inner, check)
            )
        if has_exception:
            # An `ATTR_EXC` accessor takes the state itself; the macro family
            # that carries it is the `_REF` one (no marshal shortcut is needed
            # for a value the engine may fail to produce).
            return "BINDING_ATTR_OBJECT_REF_EXC(%s, urge::%s, %s, urge::%s, "                    "k%sDataType, %s);" % (
                       owner, owner, name, inner, inner, check)
        macro = "BINDING_ATTR_OBJECT" if inner in marshalable else "BINDING_ATTR_OBJECT_REF"
        return "%s(%s, urge::%s, %s, urge::%s, k%sDataType, %s);" % (
            macro, owner, owner, name, inner, inner, check,
        )
    prefix = "BINDING_CLASS_ATTR" if static else "BINDING_ATTR"
    # A vector attribute names its element as a fourth argument, so it does not
    # go through the one suffix per type below.
    element = vector_codec(cpp_type)
    if element is not None:
        return "%s_VECTOR(%s, urge::%s, %s, %s);" % (
            prefix, owner, owner, name, element,
        )
    if cpp_type in INT_RETURNS:
        suffix = "INT"
    elif cpp_type in ("float", "double"):
        suffix = "FLOAT"
    elif cpp_type == "bool":
        suffix = "BOOL"
    else:
        raise ValueError("no attribute macro for %r" % cpp_type)
    if has_exception:
        if static:
            raise ValueError("no static ATTR_EXC macro yet: %s.%s" %
                             (owner, name))
        return "BINDING_ATTR_%s_EXC(%s, urge::%s, %s);" % (
            suffix, owner, owner, name)
    return "%s_%s(%s, urge::%s, %s);" % (prefix, suffix, owner, owner, name)


def emit_constants(owner: str, entry: dict, receiver: str) -> list[str]:
    """`rb_const_set` for every `URGE_BINDING()` marked enum enumerator.

    The value is read from the C++ enumerator (`urge::Owner::Enumerator`)
    rather than re-evaluated from the header text, so an enum with an implicit
    successor is right without the generator having to know C++ rules.
    """
    lines: list[str] = []
    for const in entry.get("constants", []):
        lines.append(
            '  rb_const_set(%s, rb_intern("%s"),' % (receiver, const["name"])
        )
        lines.append(
            "               LONG2NUM(static_cast<long>(urge::%s::%s)));"
            % (owner, const["cpp_name"])
        )
    return lines


def emit_init_function(entry: dict) -> list[str]:
    name = entry["cpp_name"]
    lines = [
        # The tail block is written after this one in the file, so the call
        # below needs the declaration.
        "void Init%sBindingAppend(VALUE klass);" % name,
        "",
        "void Init%sBinding() {" % name,
    ]
    if entry["ruby_superclass"] == "Object":
        lines.append('  auto klass = rb_define_class("%s", rb_cObject);' % name)
    else:
        lines.append(
            '  auto parent = rb_const_get(rb_cObject, rb_intern("%s"));'
            % entry["ruby_superclass"]
        )
        lines.append('  auto klass = rb_define_class("%s", parent);' % name)
    lines.append("  rb_define_alloc_func(klass, ClassAllocate<&k%sDataType>);" % name)
    lines.append("")

    if entry["constructors"]:
        lines.append('  DefineMethod(klass, "initialize", %s_initialize);' % name)
    if entry["initialize_copy"]:
        lines.append('  DefineMethod(klass, "initialize_copy", %s_initialize_copy);' % name)
    for group in group_overloads(entry["instance_methods"]):
        lines.append(
            '  DefineMethod(klass, "%s", %s_%s);'
            % (group[0]["ruby_name"], name, group[0]["cpp_name"])
        )
    for key in ("get", "set"):
        item = (entry["index"] or {}).get(key)
        if item:
            lines.append(
                '  DefineMethod(klass, "%s", %s_%s);'
                % (item["ruby_name"], name, item["cpp_name"])
            )
    if entry["marshal"]["dump"] and entry["marshal"]["load"]:
        lines.append('  DefineMethod(klass, "_dump", %s__dump);' % name)
        lines.append('  DefineClassMethod(klass, "_load", %s__load);' % name)
    if entry.get("equal"):
        for ruby_name in ("==", "eql?", "==="):
            lines.append('  DefineMethod(klass, "%s", %s__equal);' % (ruby_name, name))
    for group in group_overloads(entry["class_methods"]):
        lines.append(
            '  DefineClassMethod(klass, "%s", %s_%s);'
            % (group[0]["ruby_name"], name, group[0]["cpp_name"])
        )
    for attr in entry["attributes"]:
        lines.append('  DefineMethod(klass, "%s", %s_%s);' % (attr["name"], name, attr["cpp_name"]))
        lines.append(
            '  DefineMethod(klass, "%s", %s_%sEqual);' % (attr["setter"], name, attr["cpp_name"])
        )
    for attr in entry["class_attributes"]:
        lines.append(
            '  DefineClassMethod(klass, "%s", %s_%s);' % (attr["name"], name, attr["cpp_name"])
        )
        lines.append(
            '  DefineClassMethod(klass, "%s", %s_%sEqual);'
            % (attr["setter"], name, attr["cpp_name"])
        )
    lines.extend(emit_constants(name, entry, "klass"))
    lines.extend("  " + call for call in EXTRA_INIT_CALLS.get(name, []))
    lines.append("  Init%sBindingAppend(klass);" % name)
    lines.append("}")
    return lines


def emit_class(model: Model, entry: dict) -> list[str]:
    name = entry["cpp_name"]
    parent = exported_parent(model, entry)
    # The data type of a derived class points at its base's so that a value of
    # it is accepted where the base is expected; only an exported base has a
    # data type to point at.  See cruby_utils.h / Bindgen.md.
    declaration = (
        "RB_DEF_TYPE_INHERIT(%s, %s);" % (name, parent)
        if parent
        else "RB_DEF_TYPE(%s);" % name
    )
    lines = [
        "// " + "-" * 73,
        "// %s  (%s)" % (name, entry["export"]),
        "// " + "-" * 73,
        "",
        declaration,
        "",
    ]
    if entry["constructors"]:
        lines.extend(emit_initialize(entry))
        lines.append("")
    if entry["initialize_copy"]:
        lines.extend(emit_initialize_copy(entry))
        lines.append("")
    if entry["marshal"]["dump"] and entry["marshal"]["load"]:
        lines.extend(emit_marshal(entry))
        lines.append("")
    if entry.get("equal"):
        lines.extend(emit_equal(entry))
        lines.append("")
    for group in group_overloads(entry["instance_methods"]):
        lines.extend(emit_method(entry, group, False))
        lines.append("")
    for group in group_overloads(entry["class_methods"]):
        lines.extend(emit_method(entry, group, True))
        lines.append("")
    for attr in entry["attributes"]:
        lines.append("// Attribute: %s (%s)" % (attr["name"], attr["cpp_type"]))
        lines.extend(format_macro(attr_macro(entry, attr, False, model.marshalable)))
        lines.append("")
    for attr in entry["class_attributes"]:
        lines.append("// Class attribute: %s (%s)" % (attr["name"], attr["cpp_type"]))
        lines.extend(format_macro(attr_macro(entry, attr, True, model.marshalable)))
        lines.append("")
    lines.extend(emit_init_function(entry))
    return lines


