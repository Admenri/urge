def emit_module_method(klass: str, group: list[dict]) -> list[str]:
    head = group[0]
    dispatch = Dispatch(group)
    symbol = "%s_%s" % (klass, head["cpp_name"])
    receiver = "urge::%s::Get()" % klass
    return_type = head["return"]["cpp_type"]

    def call_of(args):
        return "%s.%s(%s)" % (receiver, head["cpp_name"], ", ".join(args))

    return ["RB_FUNC(%s) {" % symbol] + emit_framework(
        head["ruby_name"], dispatch, call_of, return_type,
        head.get("has_exception", False)
    ) + ["}"]


def emit_module_attribute(klass: str, fn: dict) -> list[str]:
    """Module attributes read the Singleton through `Get()`.

    The IR splits a read/write pair into two entries because the setter's own
    return type is `void`; the getter below is the entry without `setter`.
    `Attr_X()` answers `std::optional<ty>`, so the call expression dereferences
    it the same way the instance attribute macros do.
    """
    cpp_type = fn["attr_value_type"]
    getter = "urge::%s::Get().Attr_%s" % (klass, fn["cpp_name"])
    symbol = "%s_%s" % (klass, fn["cpp_name"])

    if fn.get("setter"):
        plan = ParamPlan([{"type": cpp_type, "name": "value"}])
        has_exception = fn.get("has_exception", False)
        lines = ["RB_FUNC(%sEqual) {" % symbol]
        if has_exception:
            lines.append("  urge::ExceptionState exception_state;")
        lines.append("  CheckArgc(argc, 1);")
        lines.extend("  " + d for d in plan.declarations)
        lines.extend(plan.parse_args_lines("  "))
        lines.extend("  " + c for c in plan.checks)
        lines.append("")
        lines.append("  {")
        lines.append("    %s(%s);" % (getter, ", ".join(
            (["exception_state"] if has_exception else []) + plan.args)))
        lines.append("  }")
        if has_exception:
            lines.append("  RaiseException(exception_state);")
        lines.append("")
        lines.append("  return Qnil;")
        lines.append("}")
        return lines

    has_exception = fn.get("has_exception", False)
    lines = ["RB_FUNC(%s) {" % symbol]
    if has_exception:
        lines.append("  urge::ExceptionState exception_state;")
    lines.extend(["  CheckArgc(argc, 0);", ""])
    lines.extend("  " + d for d in return_slot(cpp_type))
    if return_slot(cpp_type):
        lines.append("")
    lines.append("  {")
    lines.extend(emit_store(
        cpp_type,
        "(*%s(%s))" % (getter, "exception_state" if has_exception else ""),
        "    "))
    lines.append("  }")
    if has_exception:
        lines.append("  RaiseException(exception_state);")
    lines.append("")
    lines.extend(emit_convert(cpp_type, "  "))
    lines.append("}")
    return lines


def emit_module(entry: dict) -> list[str]:
    name = entry["cpp_name"]
    lines = [
        "// " + "-" * 73,
        "// %s  (%s)" % (name, entry["export"]),
        "// " + "-" * 73,
        "",
    ]
    plain = [f for f in entry["functions"] if not f.get("attr")]
    for group in group_overloads(plain):
        lines.extend(emit_module_method(name, group))
        lines.append("")
    for fn in entry["functions"]:
        if fn.get("attr"):
            lines.extend(emit_module_attribute(name, fn))
            lines.append("")

    # The tail block is written after this one in the file, so the call below
    # needs the declaration.
    lines.append("void Init%sBindingAppend(VALUE mod);" % name)
    lines.append("")
    lines.append("void Init%sBinding() {" % name)
    lines.append('  auto mod = rb_define_module("%s");' % name)
    lines.append("")
    for group in group_overloads(plain):
        lines.append(
            '  DefineModuleFunction(mod, "%s", %s_%s);'
            % (group[0]["ruby_name"], name, group[0]["cpp_name"])
        )
    for fn in entry["functions"]:
        if fn.get("attr"):
            lines.append(
                '  DefineModuleFunction(mod, "%s", %s_%s%s);'
                % (fn["ruby_name"], name, fn["cpp_name"], "Equal" if fn.get("setter") else "")
            )
    lines.extend(emit_constants(name, entry, "mod"))
    lines.extend("  " + call for call in EXTRA_INIT_CALLS.get(name, []))
    lines.append("  Init%sBindingAppend(mod);" % name)
    lines.append("}")
    return lines


