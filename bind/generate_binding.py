class Model:
    def __init__(self, ir: dict[str, Any]):
        self.ir = ir
        self.classes: list[dict] = list(ir["classes"])
        self.modules: list[dict] = list(ir["modules"])
        self.by_cpp_name = {c["cpp_name"]: c for c in self.classes}
        self.marshalable = {
            c["cpp_name"]
            for c in self.classes
            if c["marshal"]["dump"] and c["marshal"]["load"]
        }

    def all_entries(self) -> list[dict]:
        return self.classes + self.modules

    def references(self, entry: dict) -> list[str]:
        """C++ classes this entry passes through `RefPtr`."""
        types: set[str] = set()
        param_groups: list[list[dict]] = []
        for ctor in entry.get("constructors", []):
            param_groups.append(ctor["params"])
        if entry.get("initialize_copy"):
            param_groups.append(entry["initialize_copy"]["params"])
        for key in ("instance_methods", "class_methods", "functions", "data_attributes"):
            for item in entry.get(key, []):
                param_groups.append(item.get("params", []))
                ret = item.get("return")
                if ret:
                    types.add(ret["cpp_type"])
        for key in ("attributes", "class_attributes"):
            for item in entry.get(key, []):
                types.add(item["cpp_type"])
        for item in (entry.get("index") or {}).values():
            param_groups.append(item.get("params", []))
        for params in param_groups:
            for p in params:
                types.add(p["type"])
        names = {refptr_inner(t) for t in types}
        names.discard(None)
        names.discard(entry["cpp_name"])
        return sorted(n for n in names if n in self.by_cpp_name)


def exported_parent(model: Model, entry: dict) -> Optional[str]:
    """The C++ base class of `entry`, when that base is exported as well.

    A derived class is only accepted where its base is expected once the two
    data types are linked (see `RB_DEF_TYPE_INHERIT` in cruby_utils.h), and
    only a base this library defines can be linked.  The generated data type
    of a class whose base is not exported -- `Object`, `Singleton<T>` -- is
    emitted without one.  The check is the same one `check_base_order` makes
    on the registration order: the parent has to be a class of the IR.
    """
    parent = entry.get("cpp_parent")
    return parent if parent in model.by_cpp_name else None


