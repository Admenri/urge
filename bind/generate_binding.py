def snake(name: str) -> str:
    out = []
    for i, c in enumerate(name):
        if c.isupper():
            if i > 0 and (
                name[i - 1].islower() or (i + 1 < len(name) and name[i + 1].islower())
            ):
                out.append("_")
            out.append(c.lower())
        else:
            out.append(c)
    return "".join(out)


def refptr_inner(cpp_type: str) -> Optional[str]:
    m = REFPTR_RE.match(cpp_type.strip())
    return m.group("inner") if m else None


def split_top_level(text: str, sep: str = ",") -> list[str]:
    parts: list[str] = []
    depth = 0
    cur: list[str] = []
    for c in text:
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == sep and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(c)
    parts.append("".join(cur))
    return parts


def emit_call(call: str, indent: str, width: int = 80) -> list[str]:
    """Lay out a call statement, packing arguments onto continuation lines.

    `call` is the whole statement text without the trailing semicolon; the
    semicolon is added to the last line.
    """
    call = call + ";"
    line = indent + call
    if len(line) <= width or "(" not in call:
        return [line]
    paren = call.index("(")
    head = call[: paren + 1]
    args = split_top_level(call[paren + 1 : -2])
    continuation = indent + "    "
    if len(args) < 2:
        # A single argument that does not fit -- a nested call, usually. The only
        # break available is the outer parenthesis.
        if not args[0].strip():
            return [line]
        return [indent + head, continuation + args[0].strip() + ");"]
    lines: list[str] = []
    current = indent + head
    for i, arg in enumerate(args):
        piece = arg.strip() + ("," if i + 1 < len(args) else ");")
        separator = "" if current.endswith("(") else " "
        if not current.endswith("(") and len(current) + len(separator) + len(piece) > width:
            lines.append(current)
            current = continuation + piece
        else:
            current = current + separator + piece
    lines.append(current)
    return lines


def format_macro(text: str, indent: str = "", width: int = 80) -> list[str]:
    """One macro invocation, one argument per line (aligned) when too long."""
    line = indent + text
    if len(line) <= width or "(" not in text:
        return [line]
    paren = text.index("(")
    head = text[: paren + 1]
    args = split_top_level(text[paren + 1 : -2])
    if len(args) < 2:
        return [line]
    pad = " " * len(head)
    lines = [indent + head + args[0].strip() + ","]
    for arg in args[1:-1]:
        lines.append(indent + pad + arg.strip() + ",")
    lines.append(indent + pad + args[-1].strip() + ");")
    return lines


